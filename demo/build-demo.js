/* Builds the front-end-only ZamMove demo (no server needed).
     node demo/build-demo.js      (or: npm run demo)
   - engine.js: the real business rules (backend/src/domain, views, geo) bundled for the browser with a tiny
     CommonJS loader, plus demo/src/server.js (answers the API in the browser) and util-browser.js.
   - app/:      a copy of the current frontend (frontend/customer css, js, vendor).
   - index.html: the frontend's page, wired to the in-browser engine instead of the network.
   Run it again after changing the frontend or the business rules. */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const BE = path.join(ROOT, 'backend', 'src');
const FE = path.join(ROOT, 'frontend', 'customer');
const OUT = __dirname;

/* ---------- 1. engine.js ---------- */
const mods = {};
fs.readdirSync(path.join(BE, 'domain'))
  .filter(f => f.endsWith('.js'))
  .forEach(f => (mods['domain/' + f] = path.join(BE, 'domain', f)));
mods['views.js'] = path.join(BE, 'views.js');
mods['geo.js'] = path.join(BE, 'geo.js');
mods['util.js'] = path.join(OUT, 'src', 'util-browser.js'); // replaces backend/src/util.js (Node crypto)
mods['server.js'] = path.join(OUT, 'src', 'server.js');

const resolve = (from, spec) => {
  if (!spec.startsWith('.')) throw new Error(`${from}: "${spec}" is not available in the browser demo`);
  const base = path.posix.normalize(path.posix.join(path.posix.dirname(from), spec));
  for (const c of [base, base + '.js', base + '/index.js']) if (mods[c]) return c;
  throw new Error(`${from}: cannot find "${spec}"`);
};
const defs = Object.entries(mods).map(([name, file]) => {
  const src = fs.readFileSync(file, 'utf8');
  /* map every require() to its bundled module name now, so the browser does no path work */
  const map = {};
  src.replace(/require\((['"])([^'"]+)\1\)/g, (m, q, spec) => (map[spec] = resolve(name, spec)));
  return `${JSON.stringify(name)}: [${JSON.stringify(map)}, function (module, exports, require) {\n${src}\n}]`;
});
const engine = `/* generated by demo/build-demo.js on ${new Date().toISOString()}; do not edit by hand.
   The ZamMove business rules (backend/src) running in the browser for the front-end demo. */
(function () {
  'use strict';
  var process = { env: { GEO_USER_AGENT: 'ZamMove demo' } };
  var defs = {
${defs.join(',\n')}
  };
  var cache = {};
  function load(name) {
    if (cache[name]) return cache[name].exports;
    var d = defs[name], module = { exports: {} };
    cache[name] = module;
    d[1](module, module.exports, function (spec) { return load(d[0][spec]); });
    return module.exports;
  }
  load('server.js');
})();
`;
fs.writeFileSync(path.join(OUT, 'engine.js'), engine);

/* ---------- 2. app/: the current frontend ---------- */
const copyDir = (from, to) => {
  fs.mkdirSync(to, { recursive: true });
  for (const f of fs.readdirSync(from)) {
    const a = path.join(from, f),
      b = path.join(to, f);
    if (fs.statSync(a).isDirectory()) copyDir(a, b);
    else fs.copyFileSync(a, b);
  }
};
for (const d of ['css', 'js', 'vendor']) copyDir(path.join(FE, d), path.join(OUT, 'app', d));
fs.copyFileSync(path.join(OUT, 'src', 'demo-api.js'), path.join(OUT, 'demo-api.js'));
fs.copyFileSync(path.join(OUT, 'src', 'demo-panel.js'), path.join(OUT, 'demo-panel.js'));

/* ---------- 3. index.html ---------- */
let html = fs.readFileSync(path.join(FE, 'index.html'), 'utf8');
const swap = (a, b) => {
  if (!html.includes(a)) throw new Error('index.html: cannot find ' + a);
  html = html.split(a).join(b);
};
swap('href="css/', 'href="app/css/');
swap('src="js/', 'src="app/js/');
swap('src="vendor/', 'src="app/vendor/');
swap(
  '<script src="../shared/api.js"></script>',
  '<!-- front-end demo: the real business rules run in the browser (engine.js) instead of on a server -->\n    <script src="seed.js"></script>\n    <script src="engine.js"></script>\n    <script src="demo-api.js"></script>'
);
swap('<title>ZamMove – Customer &amp; Self-Drive Rental</title>', '<title>ZamMove – Demo (no server)</title>');
html = html.replace(/(\s*)<\/body>/, '$1  <script src="demo-panel.js"></script>$1</body>');
fs.writeFileSync(path.join(OUT, 'index.html'), html);

const kb = f => Math.round(fs.statSync(path.join(OUT, f)).size / 1024);
console.log(`demo built: ${Object.keys(mods).length} engine modules (${kb('engine.js')} KB), frontend copied to demo/app, open demo/index.html`);
