import { chromium } from 'playwright-core';
import fs from 'fs'; fs.mkdirSync('rw',{recursive:true});
const B='http://localhost:3100', sleep=ms=>new Promise(r=>setTimeout(r,ms));
for (let i=0;i<40;i++){try{await fetch(B+'/api/health');break;}catch{await sleep(400);}}
let fails=0; const ok=(c,m)=>{console.log((c?'PASS ':'FAIL ')+m); if(!c) fails++;};
const br=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const errs=[];
const login=async(p,em,ws,wp)=>{await p.goto(B+'/customer/'); await sleep(900); const r=await p.evaluate(em=>ZAPI.auth('login',{em,pw:'Demo1234'}),em); await p.evaluate(([me,ws,wp])=>{S.me=me;S.ws=ws;S.wp=S.wp||{}; if(wp) S.wp[ws]=wp; save(); render();},[r.me,ws,wp]); await sleep(1100); await p.evaluate(()=>ZAPI.refresh().then(()=>render())); await sleep(700);};
const act=(p,n,x)=>p.evaluate(([n,x])=>ZAPI.act(n,x),[n,x]);
const day=d=>new Date(Date.now()+d*864e5+8*36e5).toISOString().slice(0,10);
const C=await br.newPage({viewport:{width:1366,height:900}}); C.on('pageerror',e=>errs.push(e.message));
await login(C,'customer@zammove.test','customer');
const pic=await C.evaluate(()=>{const c=document.createElement('canvas');c.width=c.height=8;return c.toDataURL('image/jpeg');});
const veh=await C.evaluate(()=>(S.rentList||[])[0]); const vid=veh.id||veh.veh||veh;
const cr=await act(C,'createRental',{veh:vid,s:day(40),e:day(41),pu:'Tetuan, Zamboanga City',rt:'Putik, Zamboanga City',lic:'N01-23-456789',exp:day(400),ip:pic,lp:pic});
if(!cr.ok) throw new Error(cr.err+' '+JSON.stringify(veh).slice(0,200));
const id=cr.id;
await C.evaluate(()=>ZAPI.refresh()); await C.evaluate(()=>{location.hash='#rent';view='rent';render();}); await sleep(1200);
const card=C.locator(`#rpa${id}`);
ok((await card.count())==0,'pending: no payment form');
ok(await C.locator('.fx-wait').first().isVisible(),'pending: waiting message shown');
await C.locator('.fx-wait').first().scrollIntoViewIfNeeded(); await C.screenshot({path:'rw/1-pending.png'});
const pay=await act(C,'rentalPay',{id,amount:100,method:'Cash'});
