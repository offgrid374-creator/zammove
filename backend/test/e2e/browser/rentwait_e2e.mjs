const O=await br.newPage(); O.on('pageerror',e=>errs.push(e.message));
await login(O,owner,'owner','rent');
const ap=await act(O,'rentalDecision',{id,act:'approve'}); ok(ap.ok,'owner approves '+(ap.err||''));
await C.evaluate(()=>ZAPI.refresh().then(()=>render())); await sleep(1000);
ok((await C.locator(`#rpa${id}`).count())==1,'approved: payment form appears');
ok(!(await C.innerText('#app')).includes('Waiting for the owner to review'),'approved: waiting message gone');
ok(!errs.length,'no page errors '+errs.join('|'));
await br.close(); console.log(fails?fails+' FAILED':'ALL PASSED');
