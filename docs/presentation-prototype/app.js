/* ZamMove interactive prototype.
   Screens are real captures of the running system (data.js, generated by build_prototype.py).
   Tours walk through each role; numbered hotspots explain what is on each screen; "Go to" follows the real flow.
   Keys: ← → screens · H hotspots · P presenter mode · O overview · 1–9 open a hotspot · Esc back. */
(() => {
  const D = window.ZM;
  const app = document.getElementById('app');
  const byId = Object.fromEntries(D.screens.map(s => [s.id, s]));
  const ROLE = {
    Public: ['#475569', '#e2e8f0'],
    Customer: ['#0f766e', '#d3eee9'],
    Driver: ['#1d4ed8', '#dbe6fe'],
    'Vehicle owner': ['#6d28d9', '#eae2fd'],
    Cashier: ['#b45309', '#fcebcf'],
    Administrator: ['#b91c1c', '#fbe0e0'],
    Phone: ['#334155', '#e2e8f0'],
    'Any user': ['#475569', '#e2e8f0'],
    'Customer / Driver': ['#0f766e', '#d3eee9'],
  };
  const st = { view: 'home', tour: null, i: 0, hs: true, present: false, open: -1, grid: false };
  const esc = s =>
    String(s == null ? '' : s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
  const roleTag = r => {
    const [c, b] = ROLE[r] || ROLE.Public;
    return `<span class="role" style="color:${c};background:${b}">${esc(r)}</span>`;
  };
  const tourOf = id => D.tours.find(t => t.id == id) || D.tours[0];
  const cur = () => byId[st.tour.ids[st.i]];

  /* ---------------- routing: #/tour/<tour>/<screen> ---------------- */
  const setHash = () => {
    const h = st.view == 'home' ? '#/' : `#/tour/${st.tour.id}/${cur().id}`;
    if (location.hash != h) history.replaceState(null, '', h);
  };
  const fromHash = () => {
    const m = location.hash.match(/^#\/tour\/([^/]+)\/([^/]+)/);
    if (m) {
      const t = tourOf(m[1]),
        i = t.ids.indexOf(m[2]);
      Object.assign(st, { view: 'tour', tour: t, i: i < 0 ? 0 : i, open: -1 });
    } else st.view = 'home';
  };

  /* ---------------- home ---------------- */
  const home = () => {
    const roles = new Set(D.screens.map(s => s.role)).size;
    const tours = D.tours
      .filter(t => t.id != 'all')
      .map(t => {
        const c = (ROLE[t.role] || ROLE.Public)[0];
        return `<button class="tour" style="--c:${c}" data-tour="${t.id}">${roleTag(t.role)}<h3>${esc(t.title)}</h3><p>${esc(t.desc)}</p><div class="meta"><span>${t.ids.length} screens · ~${Math.max(2, Math.round(t.ids.length * 0.5))} min</span><span class="go">Start →</span></div></button>`;
      })
      .join('');
    app.innerHTML = `<main class="home">
<section class="hero"><div><span class="vinta"></span><h1>ZamMove<br><span>interactive prototype</span></h1><p class="lead">${esc(D.tagline)}</p>
<div class="home-actions"><button class="btn" data-tour="all">Start the full walkthrough</button><button class="btn ghost" data-tour="move">Follow one move step by step</button></div></div>
<div class="facts"><div class="fact"><b>${D.screens.length}</b><span>real screens</span></div><div class="fact"><b>${roles}</b><span>user roles</span></div><div class="fact"><b>${D.tours.length - 1}</b><span>guided tours</span></div></div></section>
<div class="sec-title"><div><h2>Guided tours</h2><p>Each tour follows one person through the system. Numbered markers explain every screen.</p></div></div>
<div class="tours">${tours}</div>
<div class="sec-title"><div><h2>About the system</h2><p>What to tell the panel in one minute.</p></div></div>
<div class="about">${D.about.map(c => `<div class="card"><h3>${esc(c[0])}</h3>${Array.isArray(c[1]) ? `<ul>${c[1].map(x => `<li>${esc(x)}</li>`).join('')}</ul>` : `<p>${esc(c[1])}</p>`}</div>`).join('')}</div>
<div class="keys"><span><span class="kbd">←</span> <span class="kbd">→</span> previous / next screen</span><span><span class="kbd">1</span>–<span class="kbd">9</span> explain a marker</span><span><span class="kbd">H</span> hide markers</span><span><span class="kbd">P</span> presenter mode</span><span><span class="kbd">O</span> all screens</span><span><span class="kbd">Esc</span> back</span></div>
<p class="keys">Screens captured from the running ZamMove system on ${esc(D.generated)} with fictional example data. Works offline.</p>
</main>`;
  };

  /* ---------------- viewer ---------------- */
  const viewer = () => {
    const s = cur(),
      t = st.tour,
      phone = s.device == 'phone';
    const list = (() => {
      let last = '';
      return t.ids
        .map((id, i) => {
          const x = byId[id];
          const sec = x.sectionTitle != last ? `<h4>${esc((last = x.sectionTitle))}</h4>` : '';
          return `${sec}<button data-go="${i}" ${i == st.i ? 'aria-current="true"' : ''}><i>${esc(id.split('-')[0])}</i><span>${esc(x.short || x.title)}</span></button>`;
        })
        .join('');
    })();
    const hs = s.callouts
      .map(
        (c, k) =>
          `<div class="hs ${k == st.open ? 'on' : ''}" data-hs="${k}" style="left:${(c.x / s.w) * 100}%;top:${(c.y / s.h) * 100}%;width:${(c.w / s.w) * 100}%;height:${(c.h / s.h) * 100}%" title="${esc(c.title)}"><span class="n">${k + 1}</span></div>`
      )
      .join('');
    const o = s.callouts[st.open];
    const pop = o
      ? `<div class="pop" style="left:${Math.min(70, Math.max(0, (o.x / s.w) * 100))}%;top:calc(${((o.y + o.h) / s.h) * 100}% + 10px)"><b>${st.open + 1}. ${esc(o.title)}</b>${esc(o.text)}</div>`
      : '';
    const nexts = (s.next || [])
      .filter(n => byId[n[0]])
      .map(n => `<button class="btn ghost" data-jump="${esc(n[0])}"><span>${esc(n[1])}</span><span style="color:var(--muted);font-weight:500">${esc(n[0].split('-')[0])} →</span></button>`)
      .join('');
    const pct = ((st.i + 1) / t.ids.length) * 100;
    app.innerHTML = `<div class="viewer ${st.present ? 'present' : ''} ${st.hs ? '' : 'hide-hs'}">
<header class="topbar"><button class="brand" data-home title="All tours">ZamMove</button><span class="tname">${esc(t.title)}</span><span class="grow"></span><span class="count">${st.i + 1} / ${t.ids.length}</span>
<button class="btn ghost hide-sm" data-ov title="All screens (O)">Overview</button><button class="btn ghost hide-sm" data-hst aria-pressed="${st.hs}" title="Markers (H)">Markers</button><button class="btn ghost" data-pres aria-pressed="${st.present}" title="Presenter mode (P)">Present</button>
<span class="progress" style="width:${pct}%"></span></header>
<div class="main"><nav class="side" aria-label="Screens in this tour">${list}</nav>
<section class="stage" id="stage"><div class="frame ${phone ? 'phone' : ''}">${phone ? '' : `<div class="chrome"><i></i><i></i><i></i><span class="url">zammove.ph · ${esc(s.title)}</span></div>`}<div class="shot"><img src="${esc(s.img)}" alt="${esc(s.title)}" width="${s.w}" height="${s.h}">${hs}${pop}</div></div></section>
<aside class="panel">${roleTag(s.role)}<h2>${esc(s.title)}</h2>
<div class="lbl">What this screen is for</div><p>${esc(s.purpose)}</p>
${s.example ? `<div class="lbl">Example data</div><div class="example">${esc(s.example)}</div>` : ''}
${s.callouts.length ? `<div class="lbl">Point out</div><ul class="points">${s.callouts.map((c, k) => `<li><button data-hs="${k}" class="${k == st.open ? 'on' : ''}"><span class="n">${k + 1}</span><span><b>${esc(c.title)}</b><span>${esc(c.text)}</span></span></button></li>`).join('')}</ul>` : ''}
${nexts ? `<div class="lbl">Go to</div><div class="nexts">${nexts}</div>` : ''}
<div class="pager"><button class="btn ghost" data-prev ${st.i == 0 ? 'disabled' : ''}>← Back</button><button class="btn" data-next>${st.i == t.ids.length - 1 ? 'Finish' : 'Next →'}</button></div></aside></div>
${st.present ? `<div class="notes"><div class="t"><b>${esc(s.title)}</b> · ${esc(s.purpose)}</div><button class="btn ghost" data-prev ${st.i == 0 ? 'disabled' : ''}>←</button><button class="btn" data-next>${st.i == t.ids.length - 1 ? 'Finish' : 'Next →'}</button><button class="btn ghost" data-pres>Exit</button></div>` : ''}
${st.grid ? overview() : ''}</div>`;
    const nx = byId[t.ids[st.i + 1]];
    if (nx) new Image().src = nx.img; // preload the next screen
  };
  const overview = () =>
    `<div class="grid-ov" role="dialog" aria-label="All screens"><header><h2>${esc(st.tour.title)} · ${st.tour.ids.length} screens</h2><button class="btn ghost" data-ov>Close</button></header><div class="thumbs">${st.tour.ids
      .map((id, i) => `<button class="thumb" data-go="${i}" ${i == st.i ? 'aria-current="true"' : ''}><span class="im" style="background-image:url('${esc(byId[id].img)}')"></span><span class="tx"><i>${esc(id.split('-')[0])}</i>${esc(byId[id].short || byId[id].title)}</span></button>`)
      .join('')}</div></div>`;

  /* ---------------- render + actions ---------------- */
  const render = () => {
    if (st.view == 'home') home();
    else viewer();
    setHash();
  };
  const goTo = (i, keepScroll) => {
    st.i = Math.max(0, Math.min(st.tour.ids.length - 1, i));
    st.open = -1;
    st.grid = false;
    render();
    if (!keepScroll) {
      const sg = document.getElementById('stage');
      if (sg) sg.scrollTop = 0;
      window.scrollTo(0, 0);
    }
  };
  const openHs = k => {
    const s = cur();
    if (!s.callouts[k]) return;
    st.open = st.open == k ? -1 : k;
    st.hs = true;
    render();
    const el = document.querySelector(`.hs[data-hs="${k}"]`),
      sg = document.getElementById('stage');
    if (el && sg && st.open == k) {
      const r = el.getBoundingClientRect(),
        sr = sg.getBoundingClientRect();
      if (r.top < sr.top + 40 || r.bottom > sr.bottom - 120) sg.scrollBy({ top: r.top - sr.top - 120, behavior: 'smooth' });
    }
  };
  const startTour = (id, screen) => {
    const t = tourOf(id);
    Object.assign(st, { view: 'tour', tour: t, i: Math.max(0, t.ids.indexOf(screen)), open: -1, grid: false });
    render();
    window.scrollTo(0, 0);
  };
  app.addEventListener('click', e => {
    const t = e.target.closest('button,[data-hs],.hs');
    if (!t) {
      if (st.open >= 0 && !e.target.closest('.pop')) {
        st.open = -1;
        render();
      }
      return;
    }
    const d = t.dataset;
    if (d.tour) return startTour(d.tour);
    if (d.home !== undefined) {
      st.view = 'home';
      st.present = false;
      return render();
    }
    if (d.go !== undefined) return goTo(+d.go);
    if (d.hs !== undefined) return openHs(+d.hs);
    if (d.next !== undefined) return st.i == st.tour.ids.length - 1 ? ((st.view = 'home'), (st.present = false), render()) : goTo(st.i + 1);
    if (d.prev !== undefined) return goTo(st.i - 1);
    if (d.jump) {
      const i = st.tour.ids.indexOf(d.jump);
      return i >= 0 ? goTo(i) : startTour('all', d.jump);
    }
    if (d.hst !== undefined) {
      st.hs = !st.hs;
      st.open = -1;
      return render();
    }
    if (d.pres !== undefined) {
      st.present = !st.present;
      return render();
    }
    if (d.ov !== undefined) {
      st.grid = !st.grid;
      return render();
    }
  });
  document.addEventListener('keydown', e => {
    if (e.target.closest && e.target.closest('input,textarea,select')) return;
    if (st.view == 'home') {
      if (e.key == 'Enter' || e.key == 'ArrowRight') startTour('all');
      return;
    }
    const k = e.key;
    if (k == 'ArrowRight' || k == 'PageDown' || (k == ' ' && !e.shiftKey)) {
      e.preventDefault();
      if (st.i < st.tour.ids.length - 1) goTo(st.i + 1);
    } else if (k == 'ArrowLeft' || k == 'PageUp') {
      e.preventDefault();
      goTo(st.i - 1);
    } else if (k == 'h' || k == 'H') {
      st.hs = !st.hs;
      st.open = -1;
      render();
    } else if (k == 'p' || k == 'P') {
      st.present = !st.present;
      render();
    } else if (k == 'o' || k == 'O') {
      st.grid = !st.grid;
      render();
    } else if (/^[1-9]$/.test(k)) openHs(+k - 1);
    else if (k == 'Escape') {
      if (st.grid) st.grid = false;
      else if (st.open >= 0) st.open = -1;
      else if (st.present) st.present = false;
      else st.view = 'home';
      render();
    }
  });
  window.addEventListener('hashchange', () => {
    fromHash();
    render();
  });
  fromHash();
  render();
})();
